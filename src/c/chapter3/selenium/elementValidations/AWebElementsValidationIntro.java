package c.chapter3.selenium.elementValidations;

public class AWebElementsValidationIntro {
    /*
    Points to Remember
         Webpage contains different kinds of elements such as
        * dropdown list or multiple dropdown selection
        * input box
        * Inner Texts
        * Any HTML Tag

        To Validate such elements, it requires some inbuilt methods such as
        * isDisplayed() - This method helps to validate that weather web element visible within the page
            return type is boolean, no argument is required
            if the particular web element is displayed it returns true otherwise exception as noSuchElement
        * isSelected() -  This method helps to validate that weather web element interactable within the page
               return type is boolean, no argument is required
            if the particular web element is displayed it returns true otherwise exception as noSuchElement
        * isEnabled() - This method helps to validate that weather any checkbox/dropdown/radio is selected
             return type is boolean, no argument is required
            if the particular web element is displayed it returns true otherwise exception as noSuchElement
     */

}
